def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate reference-format evaluation report")
    parser.add_argument("--input", required=True, action="append",
                        help="Evaluated workbook (.xlsx); repeat for multi-evaluator merge (N>=2)")
    parser.add_argument("--output", default=None, help="Output path (default: <input>_report.xlsx)")
    parser.add_argument("--language", required=True, choices=list(LANGUAGE_CODES),
                        help="Report language code (data language of the evaluated set)")
    parser.add_argument("--model", default=None, help="Model for LLM attribution (skip or --no-llm for offline)")
    parser.add_argument("--model-protocols", default=None,
                        help="MODEL=PROTOCOL,... (chat_completions|responses|anthropic_messages)")
    parser.add_argument("--doc-dirs", nargs="*", default=None, help="Corpus dirs for 原文核验")
    parser.add_argument("--threshold", type=float, default=3.0, help="Badcase weighted-score threshold")
    parser.add_argument("--no-llm", action="store_true", help="Skip LLM; use template attribution")
    return parser.parse_args(argv)


def _detect_score_columns(headers: list[str]) -> tuple[str, list[tuple[str, str]]]:
    """Return (meta, matched (score_hdr, reason_hdr) pairs) for zh or en."""
    for language in ("zh", "en"):
        pairs = score_headers(language)
        if all(h in headers for pair in pairs for h in pair):
            return language, pairs
    raise SystemExit("Cannot find evaluation score columns (zh or en score headers)")


def _find_named_column(headers: list[str], candidates: tuple[str, ...]) -> str | None:
    for header in headers:
        if header and str(header).strip() in candidates:
            return str(header).strip()
    return None


_REVIEW_SHEET_NAMES = ("低分复核", "Review")


def _load_single(path: str) -> dict[str, Any]:
    """Load one evaluated workbook: raw frame (all rows), query rows, columns."""
    wb = load_workbook(path, data_only=True)
    eval_ws = wb.worksheets[0]
    df = pd.DataFrame(eval_ws.values)
    df = df.dropna(how="all").reset_index(drop=True)
    if df.empty:
        raise SystemExit(f"No data rows found in the first sheet of {os.path.basename(path)}")
    headers = [str(h) if h is not None else "" for h in df.iloc[0].tolist()]
    df.columns = headers
    raw_df = df.iloc[1:].reset_index(drop=True)

    language, score_pairs = _detect_score_columns(headers)
    source_cols = _detect_source_columns(headers)
    rows = _load_rows(raw_df, source_cols, score_pairs)

    wa_header = _find_named_column(headers, ("Weighted Average", "加权均分"))
    summary_header = _find_named_column(headers, ("Overall Summary", "综合评价"))

    review_df = None
    for name in _REVIEW_SHEET_NAMES:
        if name in wb.sheetnames:
            review_df = pd.DataFrame(wb[name].values)
            review_df = review_df.dropna(how="all").reset_index(drop=True)
            break

    return {
        "path": os.path.abspath(path),
        "wb": wb,
        "raw_df": raw_df,
        "headers": headers,
        "language": language,
        "score_pairs": score_pairs,
        "source_cols": source_cols,
        "rows": rows,
        "wa_header": wa_header,
        "summary_header": summary_header,
        "review_df": review_df,
    }


def _merged_rows(loaded: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Merge N evaluator row-lists into per-query merged rows.

    For each query index: merged dims = mean across evaluators (scores > 0);
    merged wa = round(mean of evaluator WAs, 2). Public fields come from the
    first evaluator (alignment is validated upstream).
    """
    first = loaded[0]["rows"]
    merged: list[dict[str, Any]] = []
    for i, base in enumerate(first):
        dims: list[list[int]] = []
        was: list[float] = []
        reasons_all: list[list[str]] = []
        for entry in loaded:
            row = entry["rows"][i]
            dims.append(row["dims"])
            was.append(row["wa"])
            reasons_all.append(row["reasons"])
        merged_dims: list[float] = []
        for d in range(5):
            valid = [dims[k][d] for k in range(len(loaded)) if dims[k][d] > 0]
            merged_dims.append(sum(valid) / len(valid) if valid else 0.0)
        valid_was = [w for w in was if w is not None]
        merged_wa = round(sum(valid_was) / len(valid_was), 2) if valid_was else None
        merged.append({
            "index": base["index"],
            "query": base["query"],
            "annotation": base["annotation"],
            "filename": base["filename"],
            "filenames": base.get("filenames") or ([base["filename"]] if base["filename"] else []),
            "retrieval": base["retrieval"],
            "answer": base["answer"],
            "dims": merged_dims,
            "reasons": reasons_all,
            "wa": merged_wa,
            "was": was,
            "empty": base["empty"],
        })
    return merged


def _raw_query_pattern(entry: dict[str, Any]) -> list[bool]:
    """Per raw row: does the query cell carry text?

    This is the block/grouped-layout signature. The merged Evaluation sheet
    fills evaluator cells by raw-row position, so every evaluator file must
    place its query texts (and blank continuation rows) on identical rows.
    """
    query_col = entry["source_cols"].get("query")
    return [bool(_cell_value(row, query_col, limit=2000)) for _, row in entry["raw_df"].iterrows()]


def _validate_alignment(loaded: list[dict[str, Any]]) -> None:
    first = loaded[0]
    for other in loaded[1:]:
        problems: list[str] = []
        if other["language"] != first["language"]:
            problems.append(f"language {other['language']} != {first['language']}")
        if other["headers"] != first["headers"]:
            problems.append("score/source column headers differ")
        if len(other["raw_df"]) != len(first["raw_df"]):
            problems.append(
                f"raw row count {len(other['raw_df'])} != {len(first['raw_df'])} "
                "(the merged Evaluation sheet aligns cells by raw row)"
            )
        elif _raw_query_pattern(other) != _raw_query_pattern(first):
            problems.append(
                "row layout differs (query cells must be blank on the same rows "
                "in every evaluator file)"
            )
        if len(other["rows"]) != len(first["rows"]):
            problems.append(f"query count {len(other['rows'])} != {len(first['rows'])}")
        else:
            for i, (a, b) in enumerate(zip(first["rows"], other["rows"])):
                if a["query"] != b["query"]:
                    problems.append(f"query #{i} differs")
                    break
                if a["answer"] != b["answer"]:
                    problems.append(f"answer #{i} differs")
                    break
        if problems:
            raise SystemExit(
                f"Cannot merge {os.path.basename(other['path'])}: "
                + "; ".join(problems) + "\nAll evaluator files must score the same evaluated set."
            )


def _detect_source_columns(headers: list[str]) -> dict[str, str]:
    found: dict[str, str] = {}
    for col in headers:
        col_lower = str(col).lower()
        for field, patterns in _COLUMN_RULES.items():
            if field in found:
                continue
            if any(re.search(pattern, col_lower) for pattern in patterns):
                found[field] = col
                break
    return found


def _cell_value(row: pd.Series, column: str | None, limit: int = 8000) -> str:
    if not column:
        return ""
    value = row.get(column)
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return ""
    text = str(value).strip()
    return text[:limit] if len(text) > limit else text


def _is_grouped_layout(df: pd.DataFrame, query_col: str | None) -> bool:
    """Block/grouped layout heuristic, mirroring kb-qa-eval's rule: more than
    30% of query cells blank means continuation rows carry chunks per block."""
    if not query_col or query_col not in df.columns:
        return False
    total = len(df)
    if total == 0:
        return False
    blank = sum(1 for _, row in df.iterrows() if not _cell_value(row, query_col, limit=2000))
    return blank / total > 0.3


def _load_rows(df: pd.DataFrame, source_cols: dict[str, str],
               score_pairs: list[tuple[str, str]]) -> list[dict[str, Any]]:
    grouped = _is_grouped_layout(df, source_cols.get("query"))
    rows: list[dict[str, Any]] = []
    pending: dict[str, Any] | None = None

    def finalize() -> None:
        """Flush an aggregated block row once its group is complete."""
        nonlocal pending
        if pending is None:
            return
        pending["retrieval"] = "\n\n---\n\n".join(pending.pop("_chunk_texts"))
        pending["filename"] = ", ".join(pending["filenames"]) if pending["filenames"] else pending["filename"]
        rows.append(pending)
        pending = None

    for i, (_, row) in enumerate(df.iterrows()):
        query = _cell_value(row, source_cols.get("query"), limit=2000)
        if query:
            finalize()
            dims: list[int] = []
            reasons: list[str] = []
            for score_hdr, reason_hdr in score_pairs:
                score = parse_score(row.get(score_hdr))
                dims.append(score if score is not None else 0)
                reasons.append(_cell_value(row, reason_hdr, limit=1000))
            has_score = any(d > 0 for d in dims)
            wa = round(weighted_from_values(dims), 2) if has_score else None
            answer = _cell_value(row, source_cols.get("answer"), limit=8000)
            filename = _cell_value(row, source_cols.get("filename"), limit=500)
            chunk = _cell_value(row, source_cols.get("chunks"), limit=8000)
            pending = {
                "index": i,
                "query": query,
                "annotation": _cell_value(row, source_cols.get("reference"), limit=8000),
                "filename": filename,
                "filenames": [filename] if filename else [],
                "_chunk_texts": [chunk] if chunk else [],
                "answer": answer,
                "dims": dims,
                "reasons": reasons,
                "wa": wa,
                "empty": not answer,
            }
        elif grouped and pending is not None:
            # Block continuation row: fold its file name and chunk text into
            # the open group so attribution/原文核验 cover every recalled file.
            filename = _cell_value(row, source_cols.get("filename"), limit=500)
            if filename and filename not in pending["filenames"]:
                pending["filenames"].append(filename)
            chunk = _cell_value(row, source_cols.get("chunks"), limit=8000)
            if chunk:
                pending["_chunk_texts"].append(chunk)
        # non-grouped blank-query rows are skipped (unchanged behavior)
    finalize()
    return rows


def _compute_stats(rows: list[dict[str, Any]], threshold: float) -> dict[str, Any]:
    dim_count = 5
    dim_scores: list[list[int]] = [[] for _ in range(dim_count)]
    weighted: list[float] = []
    for row in rows:
        if row["wa"] is None:
            continue
        weighted.append(row["wa"])
        for d in range(dim_count):
            score = row["dims"][d]
            if score > 0:
                dim_scores[d].append(score)
    dim_stats = [summarize(scores) for scores in dim_scores]
    mos = sum(weighted) / len(weighted) if weighted else 0.0
    badcases = [(r["index"], r["wa"], r["query"]) for r in rows if r["wa"] is not None and r["wa"] < threshold]
    badcase_rate = len(badcases) / len(weighted) * 100 if weighted else 0.0
    empty = sum(1 for r in rows if r["empty"])
    failed = sum(1 for r in rows if r["wa"] is None)
    return {
        "total": len(rows),
        "empty": empty,
        "failed": failed,
        "dim_scores": dim_scores,
        "dim_stats": dim_stats,
        "weighted": weighted,
        "mos": mos,
        "badcases": badcases,
        "badcase_rate": badcase_rate,
    }


def _badcase_rows(rows: list[dict[str, Any]], stats: dict[str, Any]) -> list[dict[str, Any]]:
    bad_indexes = {index for index, _wa, _q in stats["badcases"]}
    return [row for row in rows if row["index"] in bad_indexes]


def _verdict_footnote(attribution_rows: list[dict[str, Any]]) -> str:
    counts: dict[str, int] = {}
    for row in attribution_rows:
        verdict = row.get("verdict", "")
        if "A 召回问题（纯）" in verdict:
            key = "A 纯召回"
        elif "A主+B次" in verdict:
            key = "A主+B次"
        elif verdict.startswith("B"):
            key = "B 定位问题"
        elif verdict.startswith("C"):
            key = "C 库无答案"
        else:
            key = "其他"
        counts[key] = counts.get(key, 0) + 1
    parts = [f"{key} {count} 条" for key, count in counts.items()]
    return (
        "归因口径：A=检索召回问题（金标信息未召回/被截断）；"
        "B=大模型定位问题（信息在场未用对，本表均为召回缺陷前提下的次责）；"
        f"C=知识库无答案。本文件 {len(attribution_rows)} 条中：{'，'.join(parts) or '无'}"
    )


def _run_merged(args: argparse.Namespace, loaded: list[dict[str, Any]]) -> int:
    """Multi-evaluator merge: one merged workbook + merged report."""
    _validate_alignment(loaded)
    first = loaded[0]
    merged_rows = _merged_rows(loaded)
    stats = _compute_stats(merged_rows, args.threshold)
    bad_rows = _badcase_rows(merged_rows, stats)

    n = len(loaded)
    dim_labels = [bilingual_dim_label(pair[0].rsplit("-", 1)[0]) for pair in first["score_pairs"]]

    attribution_rows: list[dict[str, Any]] = []
    if bad_rows:
        doc_dirs = [os.path.abspath(d) for d in (args.doc_dirs or [])]
        doc_index = build_index(doc_dirs) if doc_dirs else {}
        api_settings = None
        if args.model and not args.no_llm:
            api_settings = load_api_settings(require_key=True)
        protocols: dict[str, str] = {}
        if args.model_protocols:
            for spec in args.model_protocols.split(","):
                if "=" in spec:
                    model, protocol = spec.split("=", 1)
                    protocols[model.strip()] = protocol.strip()
        for i, row in enumerate(bad_rows):
            if i and args.model and not args.no_llm:
                time.sleep(5)  # gentle throttle: keep gateway TPM pressure low
            coverage = coverage_summary(row["annotation"], row["retrieval"])
            valid_was = [(k, w) for k, w in enumerate(row["was"]) if w is not None]
            reason_idx = min(valid_was, key=lambda pair: pair[1])[0] if valid_was else 0
            dim_reasons = "\n".join(
                f"- {dim_labels[d]}: {row['reasons'][reason_idx][d]}" for d in range(5) if row["reasons"][reason_idx][d]
            ) or "(无)"
            original_text = ""
            if doc_index:
                original_text = read_from_index(
                    doc_index, row["filenames"] or [row["filename"]],
                    annotation=row["annotation"],
                )
            if args.model and not args.no_llm:
                prompt = build_attribution_prompt(
                    query=row["query"],
                    filename=row["filename"],
                    annotation=row["annotation"],
                    retrieval=row["retrieval"],
                    coverage_text=coverage["text"],
                    answer=row["answer"],
                    wa=row["wa"] or 0.0,
                    dim_reasons=dim_reasons,
                    original_text=original_text,
                )
                try:
                    parsed = call_attribution_model(
                        prompt,
                        model=args.model,
                        base_url=api_settings.base_url,
                        api_key=api_settings.api_key,
                        protocol=protocols.get(args.model, "chat_completions"),
                        require_verification=bool(original_text),
                    )
                    verdict = parsed.get("归因结论") or ""
                    analysis = parsed.get("归因分析") or ""
                    verification = parsed.get("原文核验") or ""
                except RuntimeError as error:
                    print(f"  [warn] attribution failed for #{row['index']}: {error}")
                    verdict, analysis = offline_attribution(coverage["text"], coverage["rate"], row["wa"] or 0.0)
                    verification = ""
            else:
                verdict, analysis = offline_attribution(coverage["text"], coverage["rate"], row["wa"] or 0.0)
                verification = ""
            wa_text = " / ".join(f"{w:.2f}" if w is not None else "-" for w in row["was"])
            attribution_rows.append({
                "query": row["query"],
                "filename": row["filename"],
                "annotation": row["annotation"],
                "retrieval": row["retrieval"],
                "coverage_text": coverage["text"],
                "answer": row["answer"],
                "wa_text": wa_text,
                "verdict": verdict,
                "analysis": analysis,
                "verification": verification,
                "reasons": "\n".join(row["reasons"][reason_idx]),
            })
            print(f"  [{i + 1}/{len(bad_rows)}] #{row['index']} wa={row['wa']:.2f} ({wa_text}) {coverage['verdict']} {verdict}")

    wb = Workbook()
    wb.remove(wb.active)
    write_merged_evaluation_sheet(wb, loaded)
    if any(entry["review_df"] is not None for entry in loaded):
        write_merged_review_sheet(wb, loaded)
    write_merged_summary_sheet(
        wb,
        language_code=args.language,
        evaluator_count=n,
        total=stats["total"],
        empty=stats["empty"],
        failed=stats["failed"],
        dim_labels=dim_labels,
        dim_stats=stats["dim_stats"],
        weighted=stats["weighted"],
        mos=stats["mos"],
        badcase_rate=stats["badcase_rate"],
        badcases=stats["badcases"],
        merged_rows=merged_rows,
        threshold=args.threshold,
    )
    write_attribution_sheet(
        wb,
        language_code=args.language,
        model_label=f"{n} 评测员合并",
        threshold=args.threshold,
        rows=attribution_rows,
        criteria_footnote=_verdict_footnote(attribution_rows),
    )

    input_base = os.path.splitext(first["path"])[0]
    output_path = args.output or f"{input_base}_merged_report.xlsx"
    wb.save(output_path)
    print(f"\n合并评测员: {n}   总条目: {stats['total']}  回答为空: {stats['empty']}  失败: {stats['failed']}")
    print(f"MOS（合并均分）: {stats['mos']:.2f}  Badcase率: {stats['badcase_rate']:.1f}%  ({len(stats['badcases'])} 条)")
    print(f"合并报告已写入: {output_path}")
    return 0


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    input_paths = [os.path.abspath(p) for p in args.input]
    if len(input_paths) > 1:
        loaded = [_load_single(p) for p in input_paths]
        return _run_merged(args, loaded)

