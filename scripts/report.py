"""kb-report CLI: turn evaluated workbook(s) into the reference-format report.

Usage:
    python report.py --input <evaluated.xlsx> --language zh|en|fr|ar|id|ru [options]
    python report.py --input <e1.xlsx> --input <e2.xlsx> [--input <e3.xlsx> ...] \
        --language zh|en|fr|ar|id|ru [options]

Single --input: output workbook = input workbook + 统计摘要 + Badcase归因分析.
Multiple --input (N>=2): output a *merged* multi-evaluator workbook + report in
the format of ``en_llm_sampled_100_evaluated_human_merged.xlsx``:
  - Evaluation sheet with two-row group/column header and per-evaluator
    columns 分数_k / 理由_k / 加权均分_k / 综合评价_k
  - 低分复核 sheet: stacked rows across evaluators with column union
  - 统计摘要 computed on merged (per-query mean across evaluators) scores
  - Badcase归因分析 for merged-WA badcases only, WA column lists all N
Coverage is computed objectively; 归因结论/归因分析/原文核验 are generated by
the configured model (or by templates with --no-llm).
"""

